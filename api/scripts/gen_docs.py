"""Writes docs/API.md and docs/DATA_MODEL.md from the live OpenAPI schema and SQLAlchemy metadata. Run from api/."""

from pathlib import Path

import app.models  # noqa: F401
from app.db import Base
from app.main import app

DOCS = Path(__file__).resolve().parents[2] / "docs"


def api_md() -> str:
    schema = app.openapi()
    groups: dict[str, list[str]] = {}
    for path, ops in sorted(schema["paths"].items()):
        for method, op in ops.items():
            tag = (op.get("tags") or ["other"])[0]
            summary = (op.get("summary") or "").replace("|", "/")
            groups.setdefault(tag, []).append(f"| {method.upper()} | `{path}` | {summary} |")
    out = [
        "# API",
        "",
        "Generated by `api/scripts/gen_docs.py` from the FastAPI OpenAPI schema. Interactive docs: `/docs` on a running API.",
        'Base path `/api/v1`. Auth is `Authorization: Bearer <token>`. Errors are `{"detail": ...}`.',
        "Admin routes need an admin account that signed in with its two-step code. Money is integer kobo.",
        "",
    ]
    for tag in sorted(groups):
        out += [f"## {tag}", "", "| Method | Path | Summary |", "|---|---|---|", *groups[tag], ""]
    return "\n".join(out)


def model_md() -> str:
    out = [
        "# Data model",
        "",
        "Generated by `api/scripts/gen_docs.py` from the SQLAlchemy models. Migrations live in `api/alembic/versions`.",
        "Money columns end in `_kobo` (integer). Rates end in `_bps` (basis points). Timestamps are UTC.",
        "",
    ]
    for name, table in sorted(Base.metadata.tables.items()):
        out += [f"## {name}", "", "| Column | Type | Notes |", "|---|---|---|"]
        for col in table.columns:
            notes = []
            if col.primary_key:
                notes.append("primary key")
            if col.foreign_keys:
                notes.append("-> " + ", ".join(sorted(f.target_fullname for f in col.foreign_keys)))
            if col.unique:
                notes.append("unique")
            if not col.nullable and not col.primary_key:
                notes.append("required")
            out.append(f"| {col.name} | {str(col.type)} | {', '.join(notes)} |")
        out.append("")
    return "\n".join(out)


if __name__ == "__main__":
    (DOCS / "API.md").write_text(api_md(), encoding="utf-8")
    (DOCS / "DATA_MODEL.md").write_text(model_md(), encoding="utf-8")
    print("docs written")
